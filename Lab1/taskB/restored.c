/* dc(): копирует 1024 байта буфера в массив int (Duff's device на 8). */
static void copy_to_ints(int *dst, const char *src)
{
    for (int i = 0; i < N; i++)
        dst[i] = src[i];
}

/*
 * df(): Duff's device, 128 итераций. Ветки case 6 и case 5 склеены
 * (между ними нет p++), поэтому за итерацию обрабатывается 7 элементов,
 * а не 8: всего 128 * 7 = 896 элементов, хвост 896..1023 не трогается.
 */
static void transform(int *p)
{
    for (int i = 0; i < 128 * 7; i++) {
        switch (i % 7) {
        case 0: p[i] ^= 0x63; break;
        case 1: p[i] ^= 48;   break;
        case 2: p[i] <<= 4;   break;
        case 3: p[i] <<= 2;   break;
        case 4: p[i] *= 55;   break;
        case 5: p[i] += 97;   break;   /* *p -= -97 */
        case 6: p[i] += 44;   break;
        }
    }
}

/*
 * ch(): поэлементное сравнение с эталоном. В оригинале ip() для
 * отрицательного n строит пустой список, т.е. отрицательные значения
 * сравниваются как 0 — повторяем это.
 */
static int check(const int *v)
{
    for (int i = 0; i < N; i++)
        if ((v[i] > 0 ? v[i] : 0) != expected[i])
            return 0;
    return 1;
}

int main(void)
{
    static char buf[N];
    static int v[N];

    if (!fgets(buf, N, stdin))
        return 1;
    copy_to_ints(v, buf);
    transform(v);
    return !check(v);   /* в оригинале 23 '!' подряд == один '!' */
}
